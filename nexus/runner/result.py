"""Result and stream event models for the Agent Runner."""

from typing import Any, Literal, Optional
from pydantic import BaseModel, Field


class AgentRunResult(BaseModel):
    """Structured result containing metrics and final outputs of an agent run."""

    session_id: str = Field(..., description="The session ID associated with the run")
    final_response: Optional[str] = Field(None, description="The text response from the agent")
    structured_result: Optional[dict[str, Any]] = Field(None, description="Pydantic validated output if requested")
    turns_used: int = Field(..., description="Number of loops/turns executed")
    total_tokens_in: int = Field(default=0, description="Total prompt tokens sent to LLM")
    total_tokens_out: int = Field(default=0, description="Total completion tokens generated by LLM")
    total_tokens_saved_by_rcs: int = Field(default=0, description="One-time RCS compression savings (per-TC, at summarization moment)")
    cumulative_input_tokens_saved_by_rcs: int = Field(
        default=0,
        description="Recurring input-token savings across all turns (true cost impact of RCS)"
    )
    duration_ms: int = Field(default=0, description="Execution time in milliseconds")
    status: Literal["completed", "max_turns_reached", "error", "interrupted", "paused"] = Field(
        ..., description="Execution terminal status"
    )
    error: Optional[str] = Field(None, description="Error message if run failed")
    pending_interactions: list[dict[str, Any]] = Field(
        default_factory=list,
        description="Client tools / elicitations waiting for resume (when status=paused)",
    )
    state: dict[str, Any] = Field(
        default_factory=dict,
        description="Durable checkpoint state at end of run",
    )


class AgentStreamEvent(BaseModel):
    """Incremental event yielded during a streaming agent run."""

    event_type: Literal[
        "content",
        "tool_call",
        "tool_result",
        "client_tool_call",
        "elicitation",
        "paused",
        "event",
        "final_response",
        "error",
    ] = Field(
        ..., description="Type of stream chunk payload"
    )
    content: Optional[str] = Field(None, description="Text chunk delta or final message")
    data: Optional[dict[str, Any]] = Field(None, description="Rich event details (e.g. tool arguments, token counts)")
